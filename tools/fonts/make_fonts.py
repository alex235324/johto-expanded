# Bold versions of letters whose 1-pixel gaps would fill in when thickened
# (7 columns wide, placed at the tile's left edge).
BOLD_GLYPHS = """
M ##...## ###.### ##.#.## ##.#.## ##...## ##...## ##...## .......
W ##...## ##...## ##...## ##.#.## ##.#.## ###.### ##...## .......
m ....... ....... ######. ##.#.## ##.#.## ##.#.## ##.#.## .......
w ....... ....... ##...## ##.#.## ##.#.## ##.#.## .##.##. .......
"""

# tile index (charmap code - $80) of each glyph above
TILES = {**{c: 0x00 + i for i, c in enumerate("ABCDEFGHIJKLMNOP")},
         **{c: 0x10 + i for i, c in enumerate("QRSTUVWXYZ")},
         **{c: 0x20 + i for i, c in enumerate("abcdefghijklmnop")},
         **{c: 0x30 + i for i, c in enumerate("qrstuvwxyz")},
         **{c: 0x76 + i for i, c in enumerate("0123456789")},
         "é": 0x6a, "?": 0x66, "!": 0x67, "-": 0x63, "(": 0x1a, ")": 0x1b}


def parse(text, width):
    out = {}
    for line in text.strip().splitlines():
        ch, *rows = line.split()
        assert len(rows) == 8 and all(len(r) == width for r in rows), ch
        out[ch] = [[c == "#" for c in r] for r in rows]
    return out


def draw(base, glyphs, bold):
    im = base.copy()
    overrides = parse(BOLD_GLYPHS, 7) if bold else {}
    for ch, rows in glyphs.items():
        t = TILES[ch]
        x0, y0 = (t % 16) * 8, (t // 16) * 8
        for y in range(8):
            for x in range(8):
                im.putpixel((x0 + x, y0 + y), 255)
        if ch in overrides:
            for y, row in enumerate(overrides[ch]):
                for x, on in enumerate(row):
                    if on:
                        im.putpixel((x0 + x, y0 + y), 0)
            continue
        for y in range(8):
            for x, on in enumerate(rows[y]):
                if on:
                    im.putpixel((x0 + 1 + x, y0 + y), 0)
                    if bold:
                        im.putpixel((x0 + 2 + x, y0 + y), 0)
    return im


def main():
    base = Image.open(FONT / "font.png").convert("L")
    glyphs = parse(GLYPHS, 5)
    for name, bold in (("font_narrow", False), ("font_bold", True)):
        img = draw(base, glyphs, bold).point(lambda v: 0 if v < 128 else 255).convert("1")
        img.save(FONT / f"{name}.png")
        print("wrote", f"gfx/font/{name}.png")


if __name__ == "__main__":
    main()
