#!/usr/bin/env python3
"""Generate data/battle/gen5_exp_scale.asm: r ** 2.5 * 4096 for the Gen V level ratio
r = (2L + 10) / (L + Lp + 10) (L = defeated Pokémon's level, Lp = the gainer's level).

The game computes q = r * 1024 (between 110 and 1945 for levels 1-100). Entries 0-511
cover q = 0-511 one step at a time; entries 512-895 cover q = 512-2047 in steps of 4.
"""
from pathlib import Path

out = Path(__file__).resolve().parent.parent / "data/battle/gen5_exp_scale.asm"


def q_of(i):
    return i if i < 512 else 512 + (i - 512) * 4 + 2  # middle of the 4-step bucket


vals = [round((q_of(i) / 1024) ** 2.5 * 4096) for i in range(896)]
assert max(vals) < 0x10000
lines = ["; (r ^ 2.5) * 4096 for the Gen V exp level ratio r (generated by tools/gen5_exp_table.py)",
         "; index = q for q < 512, else q / 4 + 384 (q = r * 1024)", "",
         "Gen5ExpScaleTable:", "\ttable_width 2"]
for i in range(0, 896, 8):
    lines.append("\tdw " + ", ".join(f"{v:5d}" for v in vals[i:i + 8]) + f" ; {i}")
lines.append("\tassert_table_length GEN5_EXP_TABLE_SIZE")
out.write_text("\n".join(lines) + "\n")
