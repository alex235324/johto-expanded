#!/usr/bin/env python3
"""Fairy type data: Gen 6 retypes and Fairy moves in level-up learnsets.

1. Every species #1-649 that is Fairy type from Gen 6 on gets its Gen 6 types in
   data/pokemon/base_stats/<name>.asm (Clefairy line, Jigglypuff line, Togepi line,
   Snubbull, Marill line, Mr. Mime, Ralts line, Mawile, Cottonee...).
2. The new Fairy moves (Moonblast, Dazzling Gleam, Play Rough, Draining Kiss,
   Disarming Voice, Fairy Wind) are added to every learnset that has them by
   level-up in Omega Ruby / Alpha Sapphire, at that level.

Run after import_species.py (which rewrites the Gen 3-5 base stats/learnsets).
Re-runnable: added learnset lines end in "; fairy" and are removed first.
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pokedata as P  # noqa: E402
from place_wild import const_name, vanilla_consts  # noqa: E402

REPO = P.REPO
VG_ORAS = "16"
FAIRY_MOVES = {574: "DISARMING_VOICE", 577: "DRAINING_KISS", 583: "PLAY_ROUGH", 584: "FAIRY_WIND",
               585: "MOONBLAST", 605: "DAZZLING_GLEAM"}


def label_of(const):
    return "".join(p.capitalize() for p in const.lower().split("_") if p)


def main():
    sp = P.species_table()
    V = vanilla_consts()
    C = {i: const_name(sp[i]["identifier"]) for i in range(252, 650)}
    C.update({i: c for c, i in V.items()})
    tmap = P.types_by_id()

    # ---------------------------------------------------------------- 1. retype
    cur = defaultdict(dict)
    for r in P.rows("pokemon_types"):
        pid = int(r["pokemon_id"])
        if pid <= 649:
            cur[pid][int(r["slot"])] = tmap[r["type_id"]]
    retyped = []
    for i in range(1, 650):
        t = cur[i]
        if "FAIRY" not in t.values():
            continue
        t1, t2 = t[1], t.get(2, t[1])
        f = REPO / "data/pokemon/base_stats" / f"{C[i].lower()}.asm"
        s = f.read_text()
        s2 = re.sub(r"\tdb \w+, \w+ ; type[^\n]*", f"\tdb {t1}, {t2} ; type (Gen 6)", s, count=1)
        f.write_text(s2)
        retyped.append(f"{sp[i]['name']} {t1}/{t2}")

    # ---------------------------------------------------------------- 2. learnsets
    add = defaultdict(dict)  # species -> {move: level}
    for r in P.rows("pokemon_moves"):
        if r["version_group_id"] != VG_ORAS or r["pokemon_move_method_id"] != "1":
            continue
        pid, mid = int(r["pokemon_id"]), int(r["move_id"])
        if pid <= 649 and mid in FAIRY_MOVES:
            lv = max(1, int(r["level"]))
            add[pid][FAIRY_MOVES[mid]] = min(lv, add[pid].get(FAIRY_MOVES[mid], 999))

    files = sorted((REPO / "data/pokemon").glob("evos_attacks_*.asm"))
    texts = {f: re.sub(r"\tdbw \d+, \w+ ; fairy\n", "", f.read_text()) for f in files}
    added = []
    for i, moves in sorted(add.items()):
        label = f"{label_of(C[i])}EvosAttacks:"
        f = next((f for f in files if f"\n{label}\n" in "\n" + texts[f]), None)
        if f is None:
            print(f"warning: no learnset block for {C[i]}")
            continue
        s = texts[f]
        start = s.index(label)
        end = s.index("no more level-up moves", start)
        block = s[start:end]
        lines = block.split("\n")
        first_move = next(k for k, l in enumerate(lines) if l.startswith("\tdbw "))
        for mv, lv in sorted(moves.items(), key=lambda x: x[1]):
            if re.search(rf"\tdbw \d+, {mv}\b", "\n".join(lines)):
                continue
            k = first_move
            while k < len(lines) and lines[k].startswith("\tdbw ") and int(re.match(r"\tdbw (\d+)", lines[k]).group(1)) <= lv:
                k += 1
            lines.insert(k, f"\tdbw {lv}, {mv} ; fairy")
            added.append(f"{sp[i]['name']}: {mv} at {lv}")
        texts[f] = s[:start] + "\n".join(lines) + s[end:]
    for f, s in texts.items():
        f.write_text(s)

    report = ["# Fairy type (generated by fairy.py)", "", "## Retyped (Gen 6 types)", ""]
    report += [f"- {r}" for r in retyped] + ["", "## Fairy moves added to level-up learnsets (ORAS levels)", ""]
    report += [f"- {a}" for a in added]
    (Path(__file__).resolve().parent / "fairy_report.md").write_text("\n".join(report) + "\n")
    print(f"retyped {len(retyped)} species; added {len(added)} learnset entries")


if __name__ == "__main__":
    main()
