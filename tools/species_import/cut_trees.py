#!/usr/bin/env python3
"""Write data/events/cut_trees.asm: every cuttable tree in the game, for permanent Cut.

Scans each map's .blk for the tree blocks listed in data/collision/field_move_blocks.asm
(CutTreeBlockPointers, animation 0 = tree) and gives each tree an EVENT_CUT_TREE_n flag.
Entry: map_id, flag, offset in wOverworldMapBlocks, replacement block.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def main():
    fmb = (REPO / "data/collision/field_move_blocks.asm").read_text().split("WhirlpoolBlockPointers")[0]
    ts_label = dict(re.findall(r"dbw (TILESET_\w+),\s*\.(\w+)", fmb))
    trees = {}
    for ts, lab in ts_label.items():
        body = fmb.split(f".{lab}:")[1].split("db -1")[0]
        trees[ts] = {int(f, 16): int(r, 16) for f, r, anim in re.findall(r"db \$(\w+), \$(\w+), \$?(\d+)", body) if int(anim, 16) == 0}
    tileset = dict(re.findall(r"\s*map (\w+), (TILESET_\w+),", (REPO / "data/maps/maps.asm").read_text()))
    const = dict(re.findall(r"map_attributes (\w+), (\w+),", (REPO / "data/maps/attributes.asm").read_text()))
    width = {c: int(w) for c, w in re.findall(r"map_const (\w+),\s*(\d+),", (REPO / "constants/map_constants.asm").read_text())}
    blk = dict(re.findall(r"(\w+)_Blocks:\s*\n?\s*INCBIN \"(maps/\w+\.blk)\"", (REPO / "data/maps/blocks.asm").read_text()))
    entries = []
    for name, ts in tileset.items():
        if not trees.get(ts) or name not in blk:
            continue
        data = (REPO / blk[name]).read_bytes()
        c = const[name]
        for i, b in enumerate(data):
            if b in trees[ts]:
                entries.append((c, i % width[c], i // width[c], trees[ts][b]))
    out = ["; Every cuttable tree (generated by tools/species_import/cut_trees.py).",
           "; Cutting one sets its flag; ApplyCutTrees replaces it on every map load.", "",
           "CutTreeLocations:"]
    for n, (c, x, y, repl) in enumerate(entries, 1):
        out.append(f"\tmap_id {c}\n\tdw EVENT_CUT_TREE_{n}\n"
                   f"\tdw ({y} + MAP_CONNECTION_PADDING_WIDTH) * ({c}_WIDTH + MAP_CONNECTION_PADDING_WIDTH * 2) + {x} + MAP_CONNECTION_PADDING_WIDTH\n"
                   f"\tdb ${repl:02x} ; block ({x}, {y})")
    out += ["\tdb -1 ; end", f"DEF NUM_CUT_TREES EQU {len(entries)}"]
    (REPO / "data/events/cut_trees.asm").write_text("\n".join(out) + "\n")
    print(f"{len(entries)} trees")
    return len(entries)


if __name__ == "__main__":
    main()
