#!/usr/bin/env python3
"""Generate pokecrystal16 data for the Gen 3-5 species (national #252-649).

Inputs
    tools/sprite_convert/out/<name>/     converted pics (front.png back.png shiny.pal)
    tools/species_import/data/*.csv      PokeAPI CSV dump (Gen 5 stats/types, B2W2 learnsets)
    tools/species_import/move_overrides.csv   optional: identifier,crystal_move

Outputs (all regenerated on every run)
    gfx/pokemon/<name>/{front.png,back.png,shiny.pal}
    gfx/footprints/<name>.png                      blank placeholder footprint
    data/pokemon/base_stats/<name>.asm
    data/pokemon/dex_entries/<name>.asm
    data/pokemon/{base_stats,evos_attacks,egg_moves,dex_entries}_{hoenn,sinnoh,unova}.asm
    gfx/pics_gen3_5.asm, gfx/footprints_gen3_5.asm
    generated blocks (between ";; >>> gen3-5" markers) inside the vanilla species tables
    tools/species_import/report.md                 every judgment call made

Usage:  tools/sprite_convert/.venv/bin/python tools/species_import/import_species.py
"""

from __future__ import annotations

import csv
import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import move_subs  # noqa: E402
import pokedata as P  # noqa: E402

REPO = P.REPO
SPRITES = REPO / "tools/sprite_convert/out"
FIRST, LAST = 252, 649
REGIONS = [("hoenn", 252, 386), ("sinnoh", 387, 493), ("unova", 494, 649)]
BEGIN, END = ";; >>> gen3-5 (generated by tools/species_import; do not edit by hand)", ";; <<< gen3-5"

notes: dict[str, list[str]] = defaultdict(list)


def note(topic, text):
    notes[topic].append(text)


# --------------------------------------------------------------------------- naming

def const_name(ident: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", ident.upper())


def folder_name(ident: str) -> str:
    return re.sub(r"[^a-z0-9]", "_", ident.lower())


def label_name(ident: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[^a-z0-9]", ident.lower()) if p)


def display_name(name: str) -> str:
    n = name.replace("♀", "♀").replace("♂", "♂").replace("É", "é")  # mixed case (tools/text_case)
    if len(n) > 10:
        note("names", f"{name}: longer than 10 characters, cut to {n[:10]}")
        n = n[:10]
    return n


# --------------------------------------------------------------------------- vanilla lookups

def vanilla_consts() -> dict[int, str]:
    out, idx = {}, 0
    for line in open(REPO / "constants/pokemon_constants.asm"):
        if "NUM_POKEMON" in line:
            break
        if BEGIN in line:
            break
        m = re.match(r"\s*const (\w+)", line)
        if m:
            idx += 1
            out[idx] = m.group(1)
    return out


def species_const(i: int, sp) -> str:
    return VANILLA[i] if i in VANILLA else const_name(sp[i]["identifier"])


# --------------------------------------------------------------------------- text helpers

def sanitize(text: str) -> str:
    t = text.replace("­", "").replace("\f", " ").replace("\n", " ")
    t = t.replace("POKéMON", "#MON").replace("Pokémon", "#MON").replace("POKÉMON", "#MON")
    t = t.replace("’", "'").replace("‘", "'").replace("“", "").replace("”", "").replace('"', "")
    t = t.replace("—", "-").replace("–", "-").replace("é", "é")
    t = re.sub(r"[^A-Za-z0-9 #'\-.,!?:;()/&é]", "", t)
    return re.sub(r"\s+", " ", t).strip()


def visible_len(s: str) -> int:
    return len(s.replace("#", "POKé"))


def wrap(text: str, width=18, lines=6):
    words, out, cur = text.split(), [], ""
    for w in words:
        if visible_len(w) > width:
            return None
        cand = f"{cur} {w}" if cur else w
        if visible_len(cand) <= width:
            cur = cand
        else:
            out.append(cur)
            cur = w
    if cur:
        out.append(cur)
    return out if len(out) <= lines else None


def dex_text(d) -> list[str]:
    for t in d["flavor"]:
        w = wrap(sanitize(t))
        if w:
            return w
    # nothing fits: cut at the last sentence that fits
    t = sanitize(d["flavor"][0]) if d["flavor"] else "No data."
    sentences = re.split(r"(?<=[.!?]) ", t)
    while sentences:
        w = wrap(" ".join(sentences))
        if w:
            note("dex text", f"{d['name']}: shortened flavor text to fit 6 lines")
            return w
        sentences.pop()
    w = wrap(" ".join(t.split()[:14]) + ".") or ["No data."]
    note("dex text", f"{d['name']}: flavor text truncated hard")
    return w


def dex_species(d) -> str:
    g = d["genus"].replace(" Pokémon", "")
    if len(g) > 11:
        g2 = "".join(w[:1].upper() + w[1:].lower() for w in g.replace("-", " ").split())  # TinyRaccoon
        note("dex category", f"{d['name']}: '{g}' too long, using '{g2[:11]}'")
        g = g2[:11]
    return g


def height_weight(d) -> tuple[int, int]:
    inches = round(d["height_dm"] * 3.937008)
    feet, inch = divmod(inches, 12)
    lbs10 = round(d["weight_hg"] * 2.204623)
    return feet * 100 + inch, min(lbs10, 65535)


# --------------------------------------------------------------------------- per-species data

GROWTH = {"1": "GROWTH_SLOW", "2": "GROWTH_MEDIUM_FAST", "3": "GROWTH_FAST", "4": "GROWTH_MEDIUM_SLOW",
          "5": "GROWTH_FAST", "6": "GROWTH_SLOW"}
GENDER = {-1: "GENDER_UNKNOWN", 0: "GENDER_F0", 1: "GENDER_F12_5", 2: "GENDER_F25", 4: "GENDER_F50",
          6: "GENDER_F75", 8: "GENDER_F100"}
STONES = {"FIRE_STONE", "WATER_STONE", "THUNDERSTONE", "LEAF_STONE", "MOON_STONE", "SUN_STONE"}
STONE_SUBS = {"shiny-stone": "MOON_STONE", "dusk-stone": "MOON_STONE", "dawn-stone": "SUN_STONE",
              "ice-stone": "WATER_STONE"}
LOCATION_SUBS = {"MAGNEZONE": "THUNDERSTONE", "PROBOPASS": "THUNDERSTONE", "LEAFEON": "LEAF_STONE",
                 "GLACEON": "MOON_STONE"}
INCENSE_BABIES = {298, 360, 406, 433, 438, 439, 440, 446, 458}  # need an incense to hatch in Gen 3+
# Gen 4+ trade-evolution items that don't exist in Crystal -> an existing held item with the same flavour,
# so the "trade while holding X" rule (and vanilla mons not evolving on a plain trade) is kept.
TRADE_ITEM_SUBS = {"protector": "METAL_COAT", "electirizer": "MAGNET", "magmarizer": "CHARCOAL",
                   "dubious-disc": "UP_GRADE", "reaper-cloth": "SPELL_TAG", "deep-sea-tooth": "DRAGON_FANG",
                   "deep-sea-scale": "MYSTIC_WATER", "prism-scale": "MYSTIC_WATER"}
TIME = {"": "TR_ANYTIME", "day": "TR_MORNDAY", "night": "TR_NITE"}


def tm_list(i, ls) -> list[str]:
    names = P.crystal_moves()
    rev = {v: k for k, v in names.items()}
    learn = ls[i]["any"]
    return [m for m in P.crystal_tm_moves() if rev.get(m) in learn]


def held_items(d):
    item1 = item2 = "NO_ITEM"
    for ident, rarity in d["held_items"]:
        c = P.item_const(ident)
        if not c:
            note("held items", f"{d['name']}: {ident} doesn't exist in Crystal, dropped")
            continue
        if rarity >= 50 and item1 == "NO_ITEM":
            item1 = c
        elif item2 == "NO_ITEM":
            item2 = c
    return item1, item2


def level_learnset(i, ls, subs) -> list[tuple[int, str]]:
    out, seen = [], set()
    for lvl, mid in ls[i]["level"]:
        mv = move_subs.resolve(mid, subs)
        if mv in seen:
            continue
        seen.add(mv)
        out.append((max(1, lvl), mv))
    return out


def evolutions_from(i, sp, ls, subs, learnsets_crystal):
    """Crystal evolution lines for species i (as list of asm strings)."""
    evo = P.evolutions()
    targets = [j for j in sorted(sp) if sp[j]["evolves_from"] == i and j <= LAST]
    lines = []
    if i == 265:  # Wurmple: random in Gen 3+, use the Tyrogue-style Atk/Def split instead
        note("evolutions", "Wurmple: random split -> Silcoon if Atk >= Def, Cascoon if Atk < Def (level 7)")
        return ["dbbbw EVOLVE_STAT, 7, ATK_GT_DEF, SILCOON", "dbbbw EVOLVE_STAT, 7, ATK_EQ_DEF, SILCOON",
                "dbbbw EVOLVE_STAT, 7, ATK_LT_DEF, CASCOON"]
    if i == 412:  # Burmy: gender split
        note("evolutions", "Burmy: gender split -> Wormadam if Atk < Def, Mothim otherwise (level 20)")
        return ["dbbbw EVOLVE_STAT, 20, ATK_LT_DEF, WORMADAM", "dbbbw EVOLVE_STAT, 20, ATK_GT_DEF, MOTHIM",
                "dbbbw EVOLVE_STAT, 20, ATK_EQ_DEF, MOTHIM"]
    for j in targets:
        tgt = species_const(j, sp)
        conds = evo.get(j, [])
        c = next((x for x in conds if x["trigger"] != "shed"), None)
        if c is None:
            note("evolutions", f"{sp[i]['name']} -> {sp[j]['name']}: only obtainable via Shedinja mechanic, skipped")
            continue
        who = f"{sp[i]['name']} -> {sp[j]['name']}"
        if c["trigger"] == "trade":
            item = "-1"
            if c["held_item"]:
                ci = P.item_const(c["held_item"])
                if ci:
                    item = ci
                elif P.item_const(TRADE_ITEM_SUBS.get(c["held_item"], "").lower().replace("_", "-")) or \
                        TRADE_ITEM_SUBS.get(c["held_item"]) in P.crystal_items():
                    item = TRADE_ITEM_SUBS[c["held_item"]]
                    note("evolutions", f"{who}: trade holding {c['held_item']} (not in Crystal) -> holding {item}")
                else:
                    note("evolutions", f"{who}: trade holding {c['held_item']} (not in Crystal) -> plain trade")
            if c["trade_species"]:
                note("evolutions", f"{who}: trade for a specific species -> plain trade")
            lines.append(f"dbbw EVOLVE_TRADE, {item}, {tgt}")
        elif c["trigger"] == "use-item":
            it = P.item_const(c["item"])
            if it not in STONES:
                it = STONE_SUBS.get(c["item"], "MOON_STONE")
                note("evolutions", f"{who}: {c['item']} (not in Crystal) -> {it}")
            if c["gender"]:
                note("evolutions", f"{who}: gender requirement dropped")
            lines.append(f"dbbw EVOLVE_ITEM, {it}, {tgt}")
        elif c["trigger"] == "level-up":
            if c["happiness"] or c["held_item"]:
                tr = TIME.get(c["time"], "TR_ANYTIME")
                if c["held_item"]:
                    note("evolutions", f"{who}: level up holding {c['held_item']} ({c['time'] or 'any time'}) -> high friendship")
                lines.append(f"dbbw EVOLVE_HAPPINESS, {tr}, {tgt}")
            elif c["location"]:
                it = LOCATION_SUBS.get(tgt, "THUNDERSTONE")
                note("evolutions", f"{who}: level up at a special location -> {it}")
                lines.append(f"dbbw EVOLVE_ITEM, {it}, {tgt}")
            elif c["known_move"]:
                mv = move_subs.resolve(c["known_move"], subs)
                lvl = next((l for l, m in learnsets_crystal.get(i, []) if m == mv), None) or 34
                if lvl <= 1:  # learned at level 1 (e.g. Piloswine): would evolve instantly
                    lvl = 34
                note("evolutions", f"{who}: level up knowing {mv} -> level {lvl}")
                lines.append(f"dbbw EVOLVE_LEVEL, {lvl}, {tgt}")
            elif c["party_species"]:
                note("evolutions", f"{who}: level up with a specific party member -> level 20")
                lines.append(f"dbbw EVOLVE_LEVEL, 20, {tgt}")
            elif c["min_level"]:
                if c["gender"]:
                    note("evolutions", f"{who}: gender requirement dropped")
                lines.append(f"dbbw EVOLVE_LEVEL, {c['min_level']}, {tgt}")
            elif c["beauty"]:
                note("evolutions", f"{who}: beauty -> level 30")
                lines.append(f"dbbw EVOLVE_LEVEL, 30, {tgt}")
            else:
                note("evolutions", f"{who}: unusual level-up condition -> level 30")
                lines.append(f"dbbw EVOLVE_LEVEL, 30, {tgt}")
        else:
            note("evolutions", f"{who}: trigger {c['trigger']} unsupported -> level 30")
            lines.append(f"dbbw EVOLVE_LEVEL, 30, {tgt}")
    # Feebas: B2W2 data has both beauty (old) and prism scale trade; prefer trade if listed
    return lines


def first_stage(i, sp, vanilla_first) -> int:
    cur = i
    while sp[cur]["evolves_from"]:
        prev = sp[cur]["evolves_from"]
        if prev in INCENSE_BABIES:
            break
        if prev <= 251 and cur <= 251:
            break
        cur = prev
        if cur <= 251:
            return vanilla_first.get(cur, cur)
    return cur


# --------------------------------------------------------------------------- cries

def cry(d, cries: list[str]) -> tuple[str, int, int]:
    i = d["id"]
    base = cries[(i * 7 + int(d["shape"] or 0) * 13) % len(cries)]
    pitch = ((i * 97) % 513) - 256
    length = 160 + (i * 53) % 192
    return base, pitch, length


# --------------------------------------------------------------------------- file writing

def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def replace_block(path: Path, block: str, before: str | None = None, after: str | None = None):
    """Insert/replace the generated block. Anchored before a line matching `before`
    (regex, last match) or after a line matching `after`."""
    text = path.read_text()
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", text, flags=re.S)
    lines = text.splitlines(keepends=True)
    payload = BEGIN + "\n" + block.rstrip("\n") + "\n" + END + "\n"
    idx = None
    for n, line in enumerate(lines):
        if before and re.search(before, line):
            idx = n
        if after and re.search(after, line) and idx is None:
            idx = n + 1
    if idx is None:
        raise SystemExit(f"{path}: anchor not found")
    lines.insert(idx, payload)
    path.write_text("".join(lines))


# --------------------------------------------------------------------------- main

def main():
    global VANILLA
    VANILLA = vanilla_consts()
    assert len(VANILLA) == 251, len(VANILLA)
    sp, ls = P.species_table(), P.learnsets()
    subs = move_subs.build()
    cries = [m for m in re.findall(r"const (CRY_\w+)", (REPO / "constants/cry_constants.asm").read_text())]
    vanilla_first = {}
    for n, line in enumerate(l for l in open(REPO / "data/pokemon/first_stages.asm") if re.match(r"\s*dw \w+", l)):
        if n < 251:
            vanilla_first[n + 1] = next(k for k, v in VANILLA.items() if v == line.split()[1])

    ids = list(range(FIRST, LAST + 1))
    missing = [sp[i]["identifier"] for i in ids if not (SPRITES / folder_name(sp[i]["identifier"]) / "front.png").exists()]
    if missing:
        raise SystemExit(f"missing converted sprites for: {', '.join(missing)}")

    learn_c = {i: level_learnset(i, ls, subs) for i in list(range(1, LAST + 1))}

    # ---- per-species files
    for i in ids:
        d = sp[i]
        ident, fold, lab = d["identifier"], folder_name(d["identifier"]), label_name(d["identifier"])
        g = REPO / "gfx/pokemon" / fold
        g.mkdir(parents=True, exist_ok=True)
        for f in ("front.png", "back.png", "shiny.pal"):
            shutil.copyfile(SPRITES / fold / f, g / f)
        fp = REPO / "gfx/footprints" / f"{fold}.png"
        if not fp.exists():
            Image.new("L", (16, 16), 255).save(fp)
        item1, item2 = held_items(d)
        tms = tm_list(i, ls)
        stats = d["stats"]
        if d["base_exp"] > 255:
            note("base exp", f"{d['name']}: {d['base_exp']} capped to 255")
        write(REPO / "data/pokemon/base_stats" / f"{fold}.asm", "\n".join([
            "\tdb 0 ; species ID placeholder", "",
            "\tdb {:3d}, {:3d}, {:3d}, {:3d}, {:3d}, {:3d}".format(*stats),
            "\t;   hp  atk  def  spd  sat  sdf", "",
            f"\tdb {d['types'][0]}, {d['types'][1]} ; type",
            f"\tdb {d['capture_rate']} ; catch rate",
            f"\tdb {min(255, d['base_exp'])} ; base exp",
            f"\tdb {item1}, {item2} ; items",
            f"\tdb {GENDER[d['gender_rate']]} ; gender ratio",
            "\tdb 100 ; unknown 1",
            f"\tdb {d['hatch_counter']} ; step cycles to hatch",
            "\tdb 5 ; unknown 2",
            f'\tINCBIN "gfx/pokemon/{fold}/front.dimensions"',
            "\tdw NULL, NULL ; unused (beta front/back pics)",
            f"\tdb {GROWTH[d['growth_rate']]} ; growth rate",
            f"\tdn {d['egg_groups'][0]}, {d['egg_groups'][1]} ; egg groups", "",
            "\t; tm/hm learnset",
            ("\ttmhm " + ", ".join(tms)) if tms else "\ttmhm",
            "\t; end", ""]))
        h, w = height_weight(d)
        text = dex_text(d)
        page1, page2 = text[:3], text[3:]
        body = [f'\tdb "{dex_species(d)}@" ; species name', f"\tdw {h}, {w} ; height, weight", ""]
        for n, line in enumerate(page1):
            last = n == len(page1) - 1 and not page2
            body.append(f'\t{"db  " if n == 0 else "next"} "{line}{"@" if last else ""}"')
        if page2:
            body.append("")
            for n, line in enumerate(page2):
                last = n == len(page2) - 1
                body.append(f'\t{"page" if n == 0 else "next"} "{line}{"@" if last else ""}"')
        write(REPO / "data/pokemon/dex_entries" / f"{fold}.asm", "\n".join(body) + "\n")

    # ---- region files: base data, evos/attacks, egg moves, dex entries
    firsts = {i: first_stage(i, sp, vanilla_first) for i in ids}
    for n, (region, lo, hi) in enumerate(REGIONS):
        rid = list(range(lo, hi + 1))
        R = region.capitalize()
        write(REPO / f"data/pokemon/base_stats_{region}.asm",
              f"; Gen {n + 3} base data (generated by tools/species_import)\n\n"
              f'SECTION "Base Data {R}", ROMX\n\nBaseData{R}:\n'
              + "".join(f'INCLUDE "data/pokemon/base_stats/{folder_name(sp[i]["identifier"])}.asm"\n' for i in rid)
              + ".IndirectEnd::\n")
        ev = [f"; Gen {n + 3} evolutions and learnsets (generated by tools/species_import)", "",
              f'SECTION "Evolutions and Attacks {R}", ROMX', "", f"EvosAttacksPointers{R}::"]
        ev += [f"\tdw {label_name(sp[i]['identifier'])}EvosAttacks" for i in rid] + [".IndirectEnd::"]
        for i in rid:
            ev += ["", f"{label_name(sp[i]['identifier'])}EvosAttacks:"]
            ev += [f"\t{l}" for l in evolutions_from(i, sp, ls, subs, learn_c)]
            ev += ["\tdb 0 ; no more evolutions"]
            ev += [f"\tdbw {lvl}, {mv}" for lvl, mv in learn_c[i]]
            ev += ["\tdb 0 ; no more level-up moves"]
        write(REPO / f"data/pokemon/evos_attacks_{region}.asm", "\n".join(ev) + "\n")
        eg = [f"; Gen {n + 3} egg moves (generated by tools/species_import)", "",
              f'SECTION "Egg Moves {R}", ROMX', "", f"EggMovePointers{R}::"]
        has = {}
        for i in rid:
            moves = []
            if firsts[i] == i:
                for mid in ls[i]["egg"]:
                    mv = move_subs.resolve(mid, subs)
                    if mv not in moves:
                        moves.append(mv)
            has[i] = moves
            eg.append(f"\tdw {label_name(sp[i]['identifier'])}EggMoves" if moves else f"\tdw NoEggMoves{R}")
        eg.append(".IndirectEnd::")
        for i in rid:
            if has[i]:
                eg += ["", f"{label_name(sp[i]['identifier'])}EggMoves:"] + [f"\tdw {m}" for m in has[i]] + ["\tdw -1 ; end"]
        eg += ["", f"NoEggMoves{R}:", "\tdw -1 ; end"]
        write(REPO / f"data/pokemon/egg_moves_{region}.asm", "\n".join(eg) + "\n")
        dx = [f"; Gen {n + 3} Pokedex entries (generated by tools/species_import)"]
        for k in range(0, len(rid), 48):
            chunk = rid[k:k + 48]
            dx += ["", f'SECTION "Pokedex Entries {chunk[0]:03d}-{chunk[-1]:03d}", ROMX', ""]
            dx += [f'{label_name(sp[i]["identifier"])}PokedexEntry:: INCLUDE "data/pokemon/dex_entries/{folder_name(sp[i]["identifier"])}.asm"' for i in chunk]
        write(REPO / f"data/pokemon/dex_entries_{region}.asm", "\n".join(dx) + "\n")

    # ---- pics & footprints
    pics = ["; Gen 3-5 pics (generated by tools/species_import). One floating section each."]
    for i in ids:
        lab, fold = label_name(sp[i]["identifier"]), folder_name(sp[i]["identifier"])
        pics += ["", f'SECTION "Pic {lab}", ROMX', f'{lab}Frontpic: INCBIN "gfx/pokemon/{fold}/front.animated.2bpp.lz"',
                 f'{lab}Backpic:  INCBIN "gfx/pokemon/{fold}/back.2bpp.lz"']
    write(REPO / "gfx/pics_gen3_5.asm", "\n".join(pics) + "\n")
    write(REPO / "gfx/footprints_gen3_5.asm",
          "; Gen 3-5 footprints (generated; placeholders are blank)\n\nFootprints2:\n\ttable_width TILE_1BPP_SIZE * 4\n"
          + "".join(f'INCBIN "gfx/footprints/{folder_name(sp[i]["identifier"])}.1bpp"\n' for i in ids)
          + "\tassert_table_length NUM_POKEMON - CELEBI\n")

    # ---- generated blocks in vanilla tables
    C = [species_const(i, sp) for i in ids]
    replace_block(REPO / "constants/pokemon_constants.asm",
                  "".join(f"\tconst {c:<10} ; {i:03x}\n" for c, i in zip(C, ids)), after=r"^\s*const CELEBI\b")
    replace_block(REPO / "data/pokemon/names.asm",
                  "".join(f'\tdname "{display_name(sp[i]["name"])}"\n' for i in ids), before=r"assert_table_length")
    replace_block(REPO / "data/pokemon/cries.asm",
                  "".join("\tmon_cry {:<15} {:5d}, {:4d} ; {}\n".format(cry(sp[i], cries)[0] + ",", *cry(sp[i], cries)[1:], c)
                          for i, c in zip(ids, C)), before=r"assert_table_length")
    # menu icons: tools/menu_icons/make_icons.py builds one per species
    replace_block(REPO / "data/pokemon/pic_pointers.asm",
                  "".join(f"\tdba {label_name(sp[i]['identifier'])}Frontpic\n\tdba {label_name(sp[i]['identifier'])}Backpic\n" for i in ids),
                  before=r"assert_table_length")
    replace_block(REPO / "data/pokemon/dex_entry_pointers.asm",
                  "".join(f"\tdba {label_name(sp[i]['identifier'])}PokedexEntry\n" for i in ids), before=r"assert_table_length")
    replace_block(REPO / "data/pokemon/first_stages.asm",
                  "".join(f"\tdw {species_const(firsts[i], sp)}\n" for i in ids), before=r"assert_table_length")
    replace_block(REPO / "data/pokemon/dex_order_new.asm", "".join(f"\tdw {c}\n" for c in C), before=r"assert_table_length")
    replace_block(REPO / "data/pokemon/palettes.asm",
                  "".join(f'INCBIN "gfx/pokemon/{folder_name(sp[i]["identifier"])}/normal.gbcpal", middle_colors\n'
                          f'INCLUDE "gfx/pokemon/{folder_name(sp[i]["identifier"])}/shiny.pal"\n' for i in ids),
                  before=r"assert_table_length")
    for f, lab in (("anim_pointers", "\tdw StaticMonAnimation\n"), ("idle_pointers", "\tdw StaticMonAnimationIdle\n"),
                   ("bitmask_pointers", "\tdw StaticMonBitmasks\n"), ("frame_pointers", "\tdba StaticMonFrames\n")):
        replace_block(REPO / f"gfx/pokemon/{f}.asm", lab * len(ids), before=r"assert_table_length")

    # alphabetical order: whole table regenerated
    names = {}
    for line_no, line in enumerate(open(REPO / "data/pokemon/names.asm")):
        pass
    vanilla_names = re.findall(r'dname "([^"]+)"', (REPO / "data/pokemon/names.asm").read_text().split("PokemonNames::")[1])
    allnames = {i + 1: n for i, n in enumerate(vanilla_names[:251])}
    allnames.update({i: display_name(sp[i]["name"]) for i in ids})
    order = sorted(allnames, key=lambda i: (re.sub(r"[^A-Z]", "", allnames[i].upper().replace("♀", "F").replace("♂", "M")), i))
    text = (REPO / "data/pokemon/dex_order_alpha.asm").read_text()
    head, rest = text.split("table_width 2\n", 1)
    tail = rest[rest.index("\tassert_table_length"):]
    write(REPO / "data/pokemon/dex_order_alpha.asm",
          head + "table_width 2\n" + "".join(f"\tdw {species_const(i, sp)}\n" for i in order) + tail)

    # ---- evolutions from vanilla species into new ones (inserted into kanto/johto files)
    for fname in ("evos_attacks_kanto.asm", "evos_attacks_johto.asm"):
        path = REPO / "data/pokemon" / fname
        lines = [l for l in path.read_text().splitlines(keepends=True) if "; gen3-5" not in l]
        out, cur = [], None
        for line in lines:
            m = re.match(r"(\w+)EvosAttacks:", line)
            if m:
                cur = m.group(1)
            if line.strip().startswith("db 0 ; no more evolutions") and cur:
                vid = next((k for k, v in VANILLA.items() if label_name(v.lower().replace("__", "_")) == cur or label_name(v) == cur), None)
                if vid:
                    for evo_line in evolutions_from(vid, sp, ls, subs, learn_c):
                        if any(f", {species_const(j, sp)}" in evo_line for j in ids):
                            out.append(f"\t{evo_line} ; gen3-5\n")
                cur = None
            out.append(line)
        path.write_text("".join(out))

    # ---- report
    rep = ["# Gen 3-5 import report", "",
           f"Species {FIRST}-{LAST} ({len(ids)}), Gen 5 stats/types, Black 2/White 2 learnsets.",
           "Move substitutions: see `move_substitutions.csv` (edit `move_overrides.csv` to change).", ""]
    for topic in sorted(notes):
        rep += [f"## {topic} ({len(notes[topic])})", ""] + [f"- {t}" for t in sorted(set(notes[topic]))] + [""]
    write(Path(__file__).resolve().parent / "report.md", "\n".join(rep))
    print(f"generated {len(ids)} species; notes: " + ", ".join(f"{k} {len(set(v))}" for k, v in sorted(notes.items())))


