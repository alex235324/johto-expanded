#!/usr/bin/env python3
"""Write data/moves/categories.asm: physical/special/status for every move (Gen 4+ split).

Crystal's move IDs 1-251 are the national IDs; the Fairy moves added after BEAT_UP
are mapped by name. Categories come from PokeAPI's damage_class.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pokedata as P  # noqa: E402

REPO = P.REPO
EXTRA = {"MOONBLAST": 585, "DAZZLING_GLEAM": 605, "PLAY_ROUGH": 583, "DRAINING_KISS": 577,
         "DISARMING_VOICE": 574, "FAIRY_WIND": 584}
CLASS = {"1": "MOVE_CAT_STATUS", "2": "MOVE_CAT_PHYSICAL", "3": "MOVE_CAT_SPECIAL"}


def main():
    consts = re.findall(r"\s*const (\w+)", (REPO / "constants/move_constants.asm").read_text().split("NUM_ATTACKS")[0])[1:]
    damage_class = {int(r["id"]): r["damage_class_id"] for r in P.rows("moves")}
    out = ["; Physical/special/status of each move (Gen 4+ split), indexed by move ID.",
           "; Generated by tools/species_import/move_categories.py; read with GetMoveCategory.", "",
           'SECTION "Move Categories", ROMX', "", "MoveCategories::", "\ttable_width 1"]
    for n, c in enumerate(consts, 1):
        mid = n if n <= 251 else EXTRA[c]
        out.append(f"\tdb {CLASS[damage_class[mid]]:<17} ; {c}")
    out.append("\tassert_table_length NUM_ATTACKS")
    (REPO / "data/moves/categories.asm").write_text("\n".join(out) + "\n")
    print(f"{len(consts)} moves")


if __name__ == "__main__":
    main()
